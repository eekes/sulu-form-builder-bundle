<?php

declare(strict_types=1);

namespace Eekes\Sulu\FormBuilderBundle\Infrastructure\Symfony\DependencyInjection;

use Symfony\Component\Config\Definition\Builder\TreeBuilder;
use Symfony\Component\Config\Definition\ConfigurationInterface;

/**
 * Everything a project might reasonably want to change. The defaults are what a Bootstrap 5 Sulu
 * site needs, so the only thing most projects set is the sender of the e-mails.
 */
final class Configuration implements ConfigurationInterface
{
    public const string ROOT_NODE = 'eekes_sulu_form_builder';

    public function getConfigTreeBuilder(): TreeBuilder
    {
        $treeBuilder = new TreeBuilder(self::ROOT_NODE);

        $treeBuilder->getRootNode()
            ->children()
                ->arrayNode('sender')
                    ->addDefaultsIfNotSet()
                    ->info('Default sender of notification e-mails. A notification can override it.')
                    ->children()
                        ->scalarNode('email')->defaultNull()->end()
                        ->scalarNode('name')->defaultNull()->end()
                    ->end()
                ->end()
                ->scalarNode('upload_directory')
                    ->defaultValue('%kernel.project_dir%/var/form_builder/uploads')
                    ->cannotBeEmpty()
                    ->info('Where uploaded files are kept. Keep it outside the public directory: uploads are personal data.')
                ->end()
                ->booleanNode('csrf_protection')
                    ->defaultFalse()
                    ->info('Off by default: pages with forms are cached by Sulu\'s HTTP cache, which would serve every visitor the same, soon expired, token.')
                ->end()
                ->scalarNode('success_parameter')
                    ->defaultValue('submitted')
                    ->cannotBeEmpty()
                    ->info('Query parameter the visitor is redirected with after sending a form that shows a message.')
                ->end()
                ->arrayNode('notifications')
                    ->addDefaultsIfNotSet()
                    ->info('The e-mails of notifications: the templates editors can pick per notification, and the branding they share.')
                    ->children()
                        ->scalarNode('default_template')
                            ->defaultValue('card')
                            ->cannotBeEmpty()
                            ->info('The template of a notification that does not pick one: card, plain, summary, or one of your own.')
                        ->end()
                        ->arrayNode('templates')
                            ->info('Templates of your own, by key, next to card, plain and summary. A key of the bundle replaces that template.')
                            ->useAttributeAsKey('key')
                            ->arrayPrototype()
                                ->children()
                                    ->scalarNode('label')->isRequired()->cannotBeEmpty()->info('Shown in the notification modal; a translation key in the "admin" domain, or text.')->end()
                                    ->scalarNode('template')->isRequired()->cannotBeEmpty()->info('A Twig template extending @EekesSuluFormBuilder/email/base.html.twig, or any e-mail template.')->end()
                                ->end()
                            ->end()
                        ->end()
                        ->arrayNode('branding')
                            ->addDefaultsIfNotSet()
                            ->children()
                                ->scalarNode('name')->defaultNull()->info('Shown at the top of the e-mail, e.g. the name of the organisation. Empty: the title of the form.')->end()
                                ->scalarNode('logo_url')->defaultNull()->info('An absolute URL of a logo (PNG or JPG, about 64 px high); shown instead of the name.')->end()
                                ->scalarNode('accent_color')->defaultValue('#2563eb')->info('The colour of the top bar, headings, links and buttons.')->end()
                                ->scalarNode('footer')->defaultNull()->info('A line at the bottom of every e-mail, e.g. an address.')->end()
                            ->end()
                        ->end()
                        ->scalarNode('admin_path')
                            ->defaultValue('/admin')
                            ->info('Where the admin lives, for the "Open in the admin" link of the summary template.')
                        ->end()
                    ->end()
                ->end()
                ->arrayNode('rendering')
                    ->addDefaultsIfNotSet()
                    ->children()
                        ->scalarNode('template')->defaultValue('@EekesSuluFormBuilder/form.html.twig')->cannotBeEmpty()->end()
                        ->scalarNode('success_template')->defaultValue('@EekesSuluFormBuilder/success.html.twig')->cannotBeEmpty()->end()
                        ->scalarNode('form_theme')->defaultValue('@EekesSuluFormBuilder/form/bootstrap_5_layout.html.twig')->cannotBeEmpty()->end()
                        ->scalarNode('column_classes')
                            ->defaultValue('mb-3')
                            ->info('Added to the column classes of every field, e.g. for vertical spacing.')
                        ->end()
                        ->booleanNode('turbo_frame')
                            ->defaultFalse()
                            ->info('Wraps every form in a <turbo-frame>, so steps, errors and the success message replace only the form. A form that redirects breaks out of the frame. Can also be set per form: eekes_form(\'contact\', {turbo_frame: true}).')
                        ->end()
                        ->booleanNode('include_script')
                            ->defaultTrue()
                            ->info('Adds the script that shows and hides fields with a condition. Switch off to bundle public/js/form-builder.js yourself.')
                        ->end()
                    ->end()
                ->end()
                ->arrayNode('integrations')
                    ->addDefaultsIfNotSet()
                    ->children()
                        ->arrayNode('enabled')
                            ->info('The integrations editors may use, by key. Anything else is hidden, and its flows do not run.')
                            ->scalarPrototype()->end()
                            ->defaultValue([])
                        ->end()
                        ->booleanNode('async')
                            ->defaultTrue()
                            ->info('Dispatch runs through Symfony Messenger when it is installed. Route ExecuteIntegrationRun to an async transport to run them in a worker.')
                        ->end()
                        ->arrayNode('retry')
                            ->addDefaultsIfNotSet()
                            ->info('Automatic retries of a run that failed in a way that may pass later (a timeout, a 5xx, a 429). Needs Messenger with an async transport that supports delays.')
                            ->children()
                                ->integerNode('max_attempts')->defaultValue(3)->min(1)->info('Every attempt counts, the first included: 1 never retries automatically.')->end()
                                ->integerNode('delay')->defaultValue(60)->min(0)->info('Seconds before the first automatic retry.')->end()
                                ->floatNode('multiplier')->defaultValue(2.0)->min(1.0)->info('Each next delay is this many times longer.')->end()
                                ->integerNode('max_delay')->defaultValue(3600)->min(0)->info('The longest delay, in seconds.')->end()
                                ->arrayNode('integrations')
                                    ->info('Overrides by integration key, e.g. teamleader: { max_attempts: 5 }.')
                                    ->useAttributeAsKey('key')
                                    ->arrayPrototype()
                                        ->children()
                                            ->integerNode('max_attempts')->min(1)->end()
                                            ->integerNode('delay')->min(0)->end()
                                            ->floatNode('multiplier')->min(1.0)->end()
                                            ->integerNode('max_delay')->min(0)->end()
                                        ->end()
                                    ->end()
                                ->end()
                            ->end()
                        ->end()
                        ->arrayNode('webhook')
                            ->addDefaultsIfNotSet()
                            ->children()
                                ->floatNode('timeout')->defaultValue(10.0)->end()
                                ->scalarNode('http_client')
                                    ->defaultValue('http_client')
                                    ->cannotBeEmpty()
                                    ->info('Service id of the HTTP client webhooks are sent with, e.g. a scoped client with a proxy.')
                                ->end()
                                ->arrayNode('endpoints')
                                    ->info('Endpoints editors can pick by name. Editors never type a URL themselves.')
                                    ->useAttributeAsKey('name')
                                    ->arrayPrototype()
                                        ->beforeNormalization()
                                            ->ifString()
                                            ->then(static fn (string $url): array => ['url' => $url])
                                        ->end()
                                        ->children()
                                            ->scalarNode('url')->isRequired()->cannotBeEmpty()->end()
                                            ->scalarNode('secret')->defaultNull()->info('Signs the body: X-Eekes-Signature: sha256=<hmac>.')->end()
                                        ->end()
                                    ->end()
                                ->end()
                            ->end()
                        ->end()
                    ->end()
                ->end()
                ->arrayNode('spam_protection')
                    ->addDefaultsIfNotSet()
                    ->info('What happens to a submission a spam check caught. Which checks a form uses is set per form, in its settings.')
                    ->children()
                        ->booleanNode('log')
                            ->defaultTrue()
                            ->info('Keep blocked submissions in the "Spam" tab of the form, so a real person caught by mistake can be released. Off: they are only written to the form_builder log channel.')
                        ->end()
                        ->booleanNode('store_payload')
                            ->defaultTrue()
                            ->info('Keep what the sender filled in. Off: only the request details are kept, and a blocked submission can no longer be released.')
                        ->end()
                        ->booleanNode('anonymize_ip')
                            ->defaultFalse()
                            ->info('Store the IP address of a blocked submission with its last part zeroed.')
                        ->end()
                        ->integerNode('retention_days')
                            ->defaultValue(30)
                            ->min(0)
                            ->info('How long eekes:form-builder:prune-spam keeps blocked submissions. 0 keeps them until the command is run with --days.')
                        ->end()
                    ->end()
                ->end()
                ->arrayNode('admin')
                    ->addDefaultsIfNotSet()
                    ->children()
                        ->integerNode('navigation_position')
                            ->defaultValue(35)
                            ->info('Position of "Form builder" in the main navigation of the admin.')
                        ->end()
                    ->end()
                ->end()
            ->end()
        ;

        return $treeBuilder;
    }
}
